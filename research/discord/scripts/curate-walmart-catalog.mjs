const rows = readFileSync(INPUT, 'utf8')
  .trim()
  .split('\n')
  .map((line) => JSON.parse(line));

if (rows.length !== 266) {
  throw new Error(`Expected 266 input rows, got ${rows.length}`);
}

const kept = [];
const excluded = [];
const missing = [];

for (const row of rows) {
  const decision = DECISIONS[row.sku];
  if (!decision) {
    missing.push(row.sku);
    continue;
  }
  if ('reason' in decision) {
    excluded.push({ sku: row.sku, title: row.title ?? '', reason: decision.reason });
  } else {
    const entry = {
      sku: row.sku,
      name: decision.name,
      type: decision.type,
      set_names: decision.set_names,
      msrp_cents: decision.msrp_cents,
      msrp_confidence: decision.msrp_confidence,
      hits: row.hits,
      first_seen: row.first_seen,
    };
    if (decision.note) entry.note = decision.note;
    kept.push(entry);
  }
}

if (missing.length > 0) {
  throw new Error(`Missing decisions for ${missing.length} SKUs: ${missing.join(', ')}`);
}

kept.sort((a, b) => b.hits - a.hits);
excluded.sort((a, b) => b.hits - a.hits || a.sku.localeCompare(b.sku));

const output = { kept, excluded };
writeFileSync(OUTPUT, `${JSON.stringify(output, null, 2)}\n`);

// Summary stats
const typeDist = {};
for (const k of kept) typeDist[k.type] = (typeDist[k.type] ?? 0) + 1;
const multiSet = kept.filter((k) => k.set_names.length > 1).length;
const unknownMsrp = kept.filter((k) => k.msrp_confidence === 'unknown').length;
const reasonDist = {};
for (const e of excluded) reasonDist[e.reason] = (reasonDist[e.reason] ?? 0) + 1;

const marketplaceJunk = excluded.filter((e) =>
  /case\/display|marketplace|half booster/.test(e.reason),
).length;

